"""Single Source of Truth (SSOT) for verified physical datasheet dimensions.

Pure Python (zero external dependencies) so system Python, KiCad 10 Python,
FreeCAD 1.1 Python, Blender 5.2 Python, and web JSON exporters all read the
EXACT SAME verified mechanical specifications without hand-copied drift.

Tolerances:
  - PCB footprints, pin pitches, drill/mounting holes: +/-0.30 mm
  - Module body envelopes: +/-1.00 mm

NodeMCU variant policy (explicit):
  - This project uses ESP8266 NodeMCU v2 Amica (CP2102): PCB 48.26 x 25.40 x 1.60 mm
    (49.40 mm including Micro-USB connector overhang), 2x15 pins at 2.54 mm pitch,
    row spacing 22.86 mm (0.900 in). It does NOT use NodeMCU v3 LoLin (58 x 31 mm,
    27.94 mm / 1.100 in row spacing).

Removed legacy parts policy:
  - Zero white breadboard in the PCB-direct build.
  - Zero fan, zero AC mains relay, zero IR (VS1838B / IR LED 940 nm).
"""

