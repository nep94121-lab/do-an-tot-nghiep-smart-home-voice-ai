def get_object_slicer_overrides(part_id: str, kind: str = "panel") -> dict[str, str]:
    """Return per-object PrusaSlicer 3MF overrides for Metadata/Slic3r_PE_model.config."""
    overrides: dict[str, str] = {}
    if kind == "decorative":
        overrides["fill_density"] = "0%"
        return overrides

    if part_id in THREE_PERIMETER_PARTS:
        overrides["perimeters"] = "3"

    if part_id in WATERTIGHT_SOLID_LAYER_EXCEPTIONS:
        exc = WATERTIGHT_SOLID_LAYER_EXCEPTIONS[part_id]
        for k, v in exc.items():
            if k != "reason":
                overrides[k] = v

    return overrides


def get_effective_object_slicer_settings(part_id: str, kind: str = "panel") -> dict[str, str]:
    """Return effective merged slicer settings (global + per-object overrides) for an object."""
    eff = dict(SLICER_GLOBAL_CONFIG)
    eff.update(get_object_slicer_overrides(part_id, kind))
    return eff


def format_slic3r_pe_config() -> str:
    """Format Metadata/Slic3r_PE.config using PrusaSlicer 2.9.7's required '; key = value' syntax."""
    lines = ["; generated by PrusaSlicer 2.9.7+win64 on 2026-11-28 at 05:00:00 UTC"]
    for key, val in SLICER_GLOBAL_CONFIG.items():
        lines.append(f"; {key} = {val}")
    return "\n".join(lines) + "\n"


